#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Read every .mp4 under public/illustrations and emit a TS manifest that
// exposes each as a `data:video/mp4;base64,...` string, keyed by the
// asset name minus extension (e.g. `plan_paid-light`).
//
// The manifest is consumed by <ThemedIllustration> so we don't have to
// ship the raw .mp4 files at runtime. Necessary for hosting on Affirm's
// Quickhost (SPCS) which restricts served file types to a static whitelist
// that does NOT include .mp4.
// ---------------------------------------------------------------------------

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, "..")
const srcDir = join(repoRoot, "public", "illustrations")
const outFile = join(repoRoot, "src", "lib", "illustration-manifest.ts")

// Only inline the assets actually referenced by <ThemedIllustration> in
// the scoped scenario. Extend as needed.
const wanted = new Set([
  "plan_paid-light.mp4",
  "plan_paid-dark.mp4",
  "purchasing_power-light.mp4",
  "purchasing_power-dark.mp4",
  "money_account-light.mp4",
  "money_account-dark.mp4"
])

const files = readdirSync(srcDir).filter((f) => wanted.has(f)).sort()

if (files.length === 0) {
  console.error("No matching illustration files found in", srcDir)
  process.exit(1)
}

const entries = files.map((f) => {
  const key = f.replace(/\.mp4$/, "")
  const buf = readFileSync(join(srcDir, f))
  const b64 = buf.toString("base64")
  return { key, size: buf.length, dataUrl: `data:video/mp4;base64,${b64}` }
})

const totalBytes = entries.reduce((n, e) => n + e.size, 0)
const totalKb = Math.round(totalBytes / 1024)

const body = `// AUTO-GENERATED by scripts/inline-illustrations.mjs. Do not edit by hand.
// Regenerate with: node scripts/inline-illustrations.mjs
// Bundled MP4 illustrations as base64 data URLs so they survive static
// export + Quickhost (SPCS) hosting, which doesn't serve .mp4 files.
// Total inlined size: ~${totalKb} KB across ${entries.length} assets.

export const illustrationManifest: Record<string, string> = {
${entries.map((e) => `  ${JSON.stringify(e.key)}: ${JSON.stringify(e.dataUrl)}`).join(",\n")}
}

export const illustrationKeys = Object.keys(illustrationManifest)
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, body, "utf8")

console.log(`Wrote ${outFile}`)
console.log(`Inlined ${entries.length} assets (~${totalKb} KB total).`)
for (const e of entries) {
  console.log(`  ${e.key}  ${Math.round(e.size / 1024)} KB`)
}
